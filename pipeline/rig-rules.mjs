/**
 * 骨骼契约 — **槽位规则表**（动作库的约定层，人在环裁定，入库）
 *
 * 与材质契约同构的分工：
 *   pipeline/rig-rules.mjs     **约定**（槽位定义 / 候选骨名 / 语义轴 / 手势与物理链规则）
 *   pipeline/rig-glb.mjs       按约定解析每个模型 → assets/models/rig-manifest.json + 报告
 *   src/render/rig.ts       运行期消费（只读 manifest，**不做任何名字判定**）
 *   lab/scene/pose.html     姿势生产工具（摆 → 存 → 播）
 *
 * ⭐ 事实基础（2026-10-16 三只模型实测，`node pipeline/rig-survey.mjs <id> --core`）：
 *   ① **三只拆包模型全是 MMD 标准骨架**（日文名），语义骨名完全一致
 *      → 一份槽位表吃下所有模型。这是本项目能有一套统一动作库的根本原因。
 *   ② **权重不在语义骨上**。腿的权重在 `左足D` / `左ひざD` / `左足首D`，
 *      而 `左足` / `左ひざ` / `左足首` 权重为 0（三只全一致）。前臂扭转的权重在
 *      `腕捩1/2/3`。→ 槽位必须按「候选骨名有序表 + 有权重者优先」解析，
 *      不能按名字直取。
 *   ③ **局部轴不是语义轴**。实测：`上半身` 绕局部 X+ = 后仰、Z+ = 侧倾；
 *      `首` 绕局部 X+ = 仰头。各骨轴系互不相同。→ 动作数据一律用**语义欧拉**
 *      （俯仰/偏航/侧倾，身体空间），换算在运行期做（§语义轴换算）。
 *   ④ 骨量 386 / 828 / 620，但**值得操作的只有 20 余个槽位**，其余是物理骨
 *      （裙/发/袖/披肩，夜兰 293 根）与表情/辅助骨。
 *   ⑤ 三只模型 **morph = 0、animation = 0**：PMX 的表情与动作都没转换过来。
 *      表情要做得改 pmx2glb 导 morph；动作只能自产。
 */

