/* ------------------------------------------------------------------ *
 * ⑥ 应用逻辑（转换器与消费端共用同一套语义）
 * ------------------------------------------------------------------ */

/** 展开 `{S}` 模板（token = 左/右） */
export function expand(name, token) {
  return name.replace('{S}', token ?? '');
}

/** 全部槽位定义（成对槽位已展开为 _l/_r 两条） */
export function slotDefs() {
  const out = BODY_SLOTS.map((s) => ({ ...s, side: null, suffix: '' }));
  for (const s of SIDE_SLOTS) {
    for (const { suffix, token } of SIDES) {
      out.push({
        ...s,
        id: s.id + suffix,
        cn: s.cn + token,
        side: suffix,
        suffix,
        cands: s.cands.map((c) => expand(c, token)),
      });
    }
  }
  return out;
}

/** 手指骨定义（成对，展开后 segs 已是实际名） */
export function fingerDefs() {
  const out = [];
  for (const f of FINGERS) {
    for (const { suffix, token } of SIDES) {
      out.push({
        id: f.id + suffix,
        cn: f.cn + token,
        side: suffix,
        segs: f.segs.map((c) => expand(c, token)),
      });
    }
  }
  return out;
}
